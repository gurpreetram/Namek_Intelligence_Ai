@app.post("/scan", response_model=list[ScanResultResponse])
def scan(request: ScanRequest) -> list[ScanResultResponse]:
    """
    Scans the given symbols using whatever is currently in local cache,
    as of the most recent cached bar for each. Returns results at or
    above min_score, ranked highest first.
    """
    symbol_data = {}
    for symbol in request.symbols:
        df = storage.load(symbol)
        if df.empty:
            raise HTTPException(
                status_code=404,
                detail=f"No cached data for '{symbol}'. Fetch it first via "
                        f"data/fetcher.py or data/fetcher_yfinance.py.",
            )
        symbol_data[symbol] = df

    # as_of=None -- each symbol scanned as of ITS OWN latest cached bar,
    # not one shared timestamp across the selection. The docstring above
    # already claimed this; the code did not match it (used a single
    # max() across all selected symbols instead), which silently marks
    # every symbol whose data does not happen to reach that exact date as
    # "not enough bars today" even when it has a perfectly good, complete
    # trading day of its own -- the same staleness bug already found and
    # fixed in scan_universe()/daily_picks() elsewhere (see that
    # docstring for the real case that exposed it: 5 of 2373 symbols one
    # day ahead of the rest). Confirmed here too via a real scan that
    # returned "not enough bars yet today" for every selected symbol.
    results = scan_universe(symbol_data, as_of=None, min_score=request.min_score)

    return [
        ScanResultResponse(
            symbol=r.symbol, score=r.score, setup_type=r.setup_type,
            direction=r.direction, reasoning=r.reasoning,
        )
        for r in results
    ]


@app.get("/daily-picks", response_model=DailyPicksResponse)
def get_daily_picks(top_n: int = 5) -> DailyPicksResponse:
    """
    Scans every symbol currently in local cache and returns the top
    `top_n` long ("buy") and top `top_n` short ("sell") setups, ranked by
    the firing strategy's own confidence -- same underlying scan_universe()
    the /scan endpoint uses, just split by direction and capped at N per
    side (see detectors/scanner.py's daily_picks()).

    Each symbol is scanned as of ITS OWN most recent cached bar, not one
    shared timestamp across the universe -- a bulk-fetched cache normally
    has symbols landing on slightly different last trading days (fetched
    at different times), and forcing everyone onto a single max() timestamp
    would silently exclude every symbol that isn't exactly that fresh (see
    detectors/scanner.py's scan_universe() docstring for the real case that
    exposed this: 5 of 2373 cached symbols one day ahead of the other 2365
    caused the naive version of this endpoint to find 5 total setups
    instead of hundreds). Note this can be slow (2000+ symbols means
    2000+ per-symbol strategy replays) -- there's no caching layer here
    yet, each call re-scans the full universe from disk.
    """
    from config.settings import STORAGE_ROOT
    if not STORAGE_ROOT.exists():
        raise HTTPException(status_code=404, detail="No cached data found -- run data/bulk_fetch.py first.")

    symbols = sorted(p.stem.replace("_1min", "") for p in STORAGE_ROOT.glob("*_1min.parquet"))
    if not symbols:
        raise HTTPException(status_code=404, detail="No cached data found -- run data/bulk_fetch.py first.")

    symbol_data = {symbol: storage.load(symbol) for symbol in symbols}
    symbol_data = {s: df for s, df in symbol_data.items() if not df.empty}

    picks = daily_picks(symbol_data, as_of=None, top_n=top_n)

    def to_response(p) -> DailyPickResponse:
        return DailyPickResponse(
            symbol=p.symbol, direction=p.direction, entry_price=p.entry_price,
            stop_loss=p.stop_loss, target_price=p.target_price,
            score=p.score, setup_type=p.setup_type, reasoning=p.reasoning,
            composite_score=p.composite_score, composite_reasoning=p.composite_reasoning,
        )

    return DailyPicksResponse(
        buy=[to_response(p) for p in picks["buy"]],
        sell=[to_response(p) for p in picks["sell"]],
    )


# In-memory cache for /watchlist -- build_watchlist_parallel() takes
# ~15-20s across the full universe (see examples/run_morning_watchlist.py),
# too slow to redo on every dashboard tab-open. The watchlist is only ever
# as fresh as the local cache anyway (data/bulk_fetch.py), which doesn't
# change intraday, so recomputing more than once every few minutes buys
# nothing -- a short TTL just avoids a ~15-20s wait on every repeat load
# without risking a genuinely stale result across a trading day.
_WATCHLIST_CACHE_TTL_SECONDS = 300.0
_watchlist_cache: dict = {"items": None, "generated_at": None, "computed_at": 0.0, "status": "ok", "message": ""}


@app.get("/watchlist", response_model=WatchlistResponse)
def get_watchlist() -> WatchlistResponse:
    """
    Returns the current Phase A morning watchlist (see paper_trading/
    watchlist.py) -- confirmed picks (OpeningRangeBreakout/TrendContinuation
    that already fired) plus near-level candidates (symbols close to a
    known S/R level, worth polling live for a possible ValidatedBreakout/
    ReversalDetection confirmation -- see paper_trading/watchlist.py's
    module docstring for why those two strategies can't appear as
    confirmed picks). This recomputes the watchlist fresh (parallelized,
    cached for a few minutes -- see _WATCHLIST_CACHE_TTL_SECONDS above)
    rather than reading it from the currently-running live session
    in-process -- since selection is deterministic and the underlying
    cached data doesn't change intraday, a fresh compute always matches
    what the live session is actually polling.
    """
    from config.settings import PROJECT_ROOT, STORAGE_ROOT, now_ist
    if not STORAGE_ROOT.exists():
        raise HTTPException(status_code=404, detail="No cached data found -- run data/bulk_fetch.py first.")

    now = time.monotonic()
    if _watchlist_cache["items"] is None or (now - _watchlist_cache["computed_at"]) > _WATCHLIST_CACHE_TTL_SECONDS:
        # Cheap freshness check BEFORE paying for the full ~15-20s
        # parallelized universe scan -- same guard /sectors and
        # /market-breadth use, applied here via the sector-mapped subset
        # as a fast proxy for the whole cache's freshness (loading all
        # ~2373 symbols just for this check would double the real I/O
        # cost below). Without this, a stale cache silently produces
        # "confirmed picks" priced off yesterday's last close -- entry/
        # stop/target that look like today's live signals but aren't.
        from detectors.sector_momentum import pick_reference_as_of
        mapping_path = PROJECT_ROOT / "config" / "sector_mapping.json"
        sample_symbols = json.loads(mapping_path.read_text()) if mapping_path.exists() else []
        sample_data = {s: df for s in sample_symbols if not (df := storage.load(s)).empty}
        as_of = pick_reference_as_of(sample_data) if sample_data else None
        today_ist = now_ist().date()

        # If the live session is actively polling (fresh heartbeat), its
        # ~75 watchlist symbols genuinely have today's data even though
        # the sector-mapped SAMPLE's majority date above can still read
        # yesterday (the live session doesn't touch most of that sample
        # -- see _live_session_is_fresh()'s docstring for the confirmed
        # real case this fixes). build_watchlist_parallel() below scans
        # each symbol as of ITS OWN latest bar regardless, so bypassing
        # this gate when the live session is fresh doesn't risk treating
        # genuinely-stale symbols as current -- it just stops blocking
        # the ones that actually are current.
        if as_of is not None and as_of.date() != today_ist and not _live_session_is_fresh():
            _watchlist_cache["items"] = []
            _watchlist_cache["generated_at"] = datetime.now().isoformat()
            _watchlist_cache["computed_at"] = now
            _watchlist_cache["status"] = "stale_previous_day"
            _watchlist_cache["message"] = (
                f"Cached data hasn't been refreshed today yet -- the latest available bar is from "
                f"{as_of.date().isoformat()}. Start a live session (or re-run the bulk fetch) to see today's picks."
            )
        else:
            from examples.run_morning_watchlist import build_watchlist_parallel
            items = build_watchlist_parallel(show_progress=False)
            if not items:
                raise HTTPException(status_code=404, detail="No cached data found -- run data/bulk_fetch.py first.")
            _watchlist_cache["items"] = items
            _watchlist_cache["generated_at"] = datetime.now().isoformat()
            _watchlist_cache["computed_at"] = now
            _watchlist_cache["status"] = "ok"
            _watchlist_cache["message"] = ""

    return WatchlistResponse(
        status=_watchlist_cache["status"],
        message=_watchlist_cache["message"],
        generated_at=_watchlist_cache["generated_at"],
        items=[
            WatchlistItemResponse(symbol=w.symbol, direction=w.direction, category=w.reason,
                                   detail=w.detail, score=w.score, distance_atr=w.distance_atr,
                                   entry_price=w.entry_price, stop_loss=w.stop_loss, target_price=w.target_price,
                                   current_price=w.current_price, level_price=w.level_price,
                                   composite_score=w.composite_score, composite_reasoning=w.composite_reasoning)
            for w in _watchlist_cache["items"]
        ],
    )


# How stale paper_trading/live_poller.py's latest_prices.json is allowed
# to be before get_live_activity() stops using it for the open-position
# status indicator. The poller writes it every poll cycle (60s by
# default) -- 3x that gives headroom for one slow/failed cycle without
# either blocking on a fresh fetch (explicitly not wanted here -- see
# live_poller.py's LATEST_PRICES_PATH docstring) or showing a
# misleadingly stale "live" price.
_LATEST_PRICES_MAX_AGE_SECONDS = 180.0


def _load_latest_prices() -> dict[str, float]:
    from paper_trading.live_poller import LATEST_PRICES_PATH
    if not LATEST_PRICES_PATH.exists():
        return {}
    try:
        payload = json.loads(LATEST_PRICES_PATH.read_text())
        generated_at = datetime.fromisoformat(payload["generated_at"])
        age = (datetime.now() - generated_at).total_seconds()
        if age > _LATEST_PRICES_MAX_AGE_SECONDS:
            return {}
        return payload.get("prices", {})
    except (OSError, ValueError, KeyError):
        return {}


# How fresh paper_trading/live_poller.py's heartbeat.json must be for
# /watchlist and /strong-trend-stocks to trust the LIVE SESSION's own
# symbol set as "today's data" and bypass their normal cache-wide
# staleness gate -- see _live_session_is_fresh()'s docstring for why that
# gate false-positives during live trading hours. Deliberately a separate
# constant from _LIVE_SESSION_STALE_SECONDS (90s, used by
# /live-session-status's own "alive"/"stale" label) rather than reusing
# it: this is a different decision (safe to trust this endpoint's data
# right now) with its own threshold, even though in practice "alive"
# already implies under 120s.
_LIVE_SESSION_FRESH_OVERRIDE_SECONDS = 120.0


def _live_session_is_fresh() -> bool:
    """
    True if paper_trading/live_poller.py's heartbeat is from today and
    less than _LIVE_SESSION_FRESH_OVERRIDE_SECONDS old.

    Why this exists: /watchlist and /strong-trend-stocks each run a cheap
    pre-check -- "is today's data actually in the cache yet" -- before
    paying for their real computation, using pick_reference_as_of() over
    either a sector-mapped sample (~180 symbols) or the full cached
    universe (~2385 symbols). During live trading hours, LivePoller only
    writes fresh bars for its OWN watchlist-sized symbol set (~75 symbols,
    see paper_trading/watchlist.py) -- it never touches the other
    ~1500-2300+ symbols intraday. So the MAJORITY date across either
    check's sample is still yesterday's for as long as the live session
    runs, even though today's data genuinely exists for the ~75 symbols
    that matter for these two endpoints -- confirmed as a real, not
    hypothetical, false "stale_previous_day" while a live session with 5
    open positions was actively running.

    A fresh heartbeat is a reliable proxy that today's data exists for
    at least the live session's polled symbols specifically (LivePoller
    only heartbeats after a successful poll cycle -- see live_poller.py),
    so callers can safely bypass their cache-wide gate: the underlying
    per-symbol logic in both endpoints already scans each symbol as of
    ITS OWN latest bar (see examples/run_morning_watchlist.py's
    build_watchlist_parallel() and detectors/strong_trend.py), so a
    symbol the live session hasn't touched today simply contributes no
    result rather than being wrongly treated as fresh.
    """
    from paper_trading.live_poller import HEARTBEAT_PATH
    if not HEARTBEAT_PATH.exists():
        return False
    try:
        payload = json.loads(HEARTBEAT_PATH.read_text())
        last_heartbeat = datetime.fromisoformat(payload["timestamp"])
    except (OSError, ValueError, KeyError):
        return False
    if last_heartbeat.date() != date.today():
        return False
    age = (datetime.now() - last_heartbeat).total_seconds()
    return age <= _LIVE_SESSION_FRESH_OVERRIDE_SECONDS


def _status_indicator(current_price: float, stop_loss: float, target: float) -> str:
    dist_to_target = abs(current_price - target)
    dist_to_stop = abs(current_price - stop_loss)
    if dist_to_target < dist_to_stop:
        return "near_target"
    if dist_to_stop < dist_to_target:
        return "near_stop"
    return "near_entry"


@app.get("/live-activity", response_model=LiveActivityResponse)
def get_live_activity(limit: int = 100) -> LiveActivityResponse:
    """
    Reads paper_trading/journal.jsonl (the SAME journal PaperTradingEngine
    writes to during a live session -- see paper_trading/live_poller.py)
    and splits today's events into OPEN positions (an entry with no
    matching exit yet) and CLOSED trades (entry+exit pairs). This is
    read-only observation of what the live session already logged -- no
    trading logic lives here, matching this API layer's "expose, don't
    reimplement" rule (see module docstring).

    Open-position status_indicator uses paper_trading/live_poller.py's
    latest_prices.json (see that module for why this doesn't fetch its
    own live quote) -- current_price/status_indicator are both None when
    that file is missing, stale, or doesn't have this symbol yet (e.g. a
    live session that predates the latest_prices.json feature, or hasn't
    completed a poll cycle for this symbol yet).
    """
    journal = TradeJournal()
    df = journal.load_all()
    if df.empty:
        return LiveActivityResponse(open_positions=[], closed_trades=[])

    today = date.today()
    # entry_time is stored as a JSON string (json.dumps(default=str) in
    # journal.py), not a real datetime column -- must parse before
    # filtering/sorting.
    entry_times = pd.to_datetime(df["entry_time"])
    df = df[entry_times.dt.date == today]
    if df.empty:
        return LiveActivityResponse(open_positions=[], closed_trades=[])

    entries = df[df["event"] == "trade_entered"]
    exits = df[df["event"] == "trade_exited"]

    closed_trades: list[ClosedTradeResponse] = []
    exited_keys: set[tuple] = set()
    for _, row in exits.iterrows():
        exited_keys.add((row["symbol"], row["strategy_name"], str(row["entry_time"])))
        # exit_reasoning is a new field -- older journal rows written
        # before it existed come back as NaN (missing), not [], from
        # pandas; normalize those to [] rather than passing NaN through.
        raw_exit_reasoning = row.get("exit_reasoning")
        exit_reasoning = raw_exit_reasoning if isinstance(raw_exit_reasoning, list) else []
        closed_trades.append(ClosedTradeResponse(
            symbol=row["symbol"], strategy_name=row["strategy_name"], direction=row["direction"],
            entry_time=str(row["entry_time"]), entry_price=row["entry_price"],
            exit_time=str(row["exit_time"]), exit_price=row["exit_price"],
            exit_reason=row["exit_reason"], exit_reasoning=exit_reasoning, pnl_points=row["pnl_points"],
            r_multiple=row.get("r_multiple", 0.0),
        ))
    closed_trades.sort(key=lambda t: t.exit_time, reverse=True)

    latest_prices = _load_latest_prices()
    open_positions: list[OpenPositionResponse] = []
    for _, row in entries.iterrows():
        key = (row["symbol"], row["strategy_name"], str(row["entry_time"]))
        if key in exited_keys:
            continue  # already closed -- represented in closed_trades above
        current_price = latest_prices.get(row["symbol"])
        status = (
            _status_indicator(current_price, row["stop_loss"], row["target"])
            if current_price is not None else None
        )
        open_positions.append(OpenPositionResponse(
            symbol=row["symbol"], strategy_name=row["strategy_name"], direction=row["direction"],
            entry_time=str(row["entry_time"]), entry_price=row["entry_price"],
            stop_loss=row["stop_loss"], target=row["target"], reasoning=row.get("reasoning") or [],
            current_price=current_price, status_indicator=status,
        ))
    open_positions.sort(key=lambda t: t.entry_time, reverse=True)

    return LiveActivityResponse(
        open_positions=open_positions,
        closed_trades=closed_trades[:limit],
    )


def _pnl_status(unrealized_pnl: float) -> str:
    if unrealized_pnl > 0:
        return "profit"
    if unrealized_pnl < 0:
        return "loss"
    return "breakeven"


@app.post("/partial-exit", response_model=PartialExitResponse)
def create_partial_exit(request: PartialExitRequest) -> PartialExitResponse:
    """
    Records a partial exit the user already placed manually (e.g. in
    Kotak Neo) against an open position -- LOCAL tracking only (see
    paper_trading/partial_exits.py's module docstring), does not place,
    modify, or cancel any real order.
    """
    from paper_trading.partial_exits import add_partial_exit

    if request.direction not in ("long", "short"):
        raise HTTPException(status_code=400, detail="direction must be 'long' or 'short'")
    if request.remaining_quantity > request.total_quantity:
        raise HTTPException(status_code=400, detail="remaining_quantity cannot exceed total_quantity")

    record = add_partial_exit(
        symbol=request.symbol, direction=request.direction,
        total_quantity=request.total_quantity, exit_quantity=request.exit_quantity,
        exit_price=request.exit_price, remaining_quantity=request.remaining_quantity,
        new_stop_loss=request.new_stop_loss,
    )
    return PartialExitResponse(**asdict(record))


@app.get("/partial-exits", response_model=PartialExitsResponse)
def get_partial_exits() -> PartialExitsResponse:
    """
    Today's active partial exits (see paper_trading/partial_exits.py --
    entries from a previous day are auto-cleared on every call), enriched
    with the originating position's entry_price and a fresh current_price
    so the dashboard can show unrealized P&L on the shares still held.

    entry_price is reconciled from paper_trading/journal.jsonl using the
    SAME open-position logic get_live_activity() uses above -- reused, not
    reimplemented -- except keyed by symbol alone (the partial-exit form
    only ever has the symbol to go on, not the full (symbol, strategy_name,
    entry_time) tuple), so this is ambiguous if more than one open position
    shares a symbol. current_price comes from the same latest_prices.json
    /live-activity uses (see _load_latest_prices()). entry_price,
    current_price, and unrealized_pnl are all None together when the
    originating position can no longer be found open in the journal (e.g.
    already fully closed) or no fresh live price is available yet --
    the frontend should render that as an unknown/neutral state, not a
    real number.
    """
    from paper_trading.partial_exits import get_active_partial_exits

    records = get_active_partial_exits()
    if not records:
        return PartialExitsResponse(exits=[])

    journal = TradeJournal()
    df = journal.load_all()
    entry_price_by_symbol: dict[str, float] = {}
    if not df.empty:
        today = date.today()
        entry_times = pd.to_datetime(df["entry_time"])
        today_df = df[entry_times.dt.date == today]
        if not today_df.empty:
            entries = today_df[today_df["event"] == "trade_entered"]
            exits = today_df[today_df["event"] == "trade_exited"]
            exited_keys = {
                (row["symbol"], row["strategy_name"], str(row["entry_time"]))
                for _, row in exits.iterrows()
            }
            for _, row in entries.iterrows():
                key = (row["symbol"], row["strategy_name"], str(row["entry_time"]))
                if key not in exited_keys:
                    entry_price_by_symbol.setdefault(row["symbol"], row["entry_price"])

    latest_prices = _load_latest_prices()

    responses = []
    for r in records:
        entry_price = entry_price_by_symbol.get(r.symbol)
        current_price = latest_prices.get(r.symbol)
        unrealized_pnl = None
        pnl_status = None
        if entry_price is not None and current_price is not None:
            sign = 1.0 if r.direction == "long" else -1.0
            unrealized_pnl = (current_price - entry_price) * sign * r.remaining_quantity
            pnl_status = _pnl_status(unrealized_pnl)
        responses.append(PartialExitResponse(
            **asdict(r), entry_price=entry_price, current_price=current_price,
            unrealized_pnl=unrealized_pnl, pnl_status=pnl_status,
        ))
    return PartialExitsResponse(exits=responses)


# How stale paper_trading/live_poller.py's heartbeat.json is allowed to
# be before /live-session-status calls it "stale" rather than "alive" --
# matched to LivePoller's default 60s poll_interval_seconds with margin
# for one slow/delayed cycle, same reasoning as
# _LATEST_PRICES_MAX_AGE_SECONDS above.
_LIVE_SESSION_STALE_SECONDS = 90.0


@app.get("/live-session-status", response_model=LiveSessionStatusResponse)
def get_live_session_status() -> LiveSessionStatusResponse:
    """
    Reads paper_trading/heartbeat.json (written by LivePoller after every
    poll cycle -- see live_poller.py's HEARTBEAT_PATH docstring) and
    reports whether a live session is actually running right now, rather
    than letting the dashboard silently show old data as if it were
    current. Built after a real incident: a prior live session died
    (process torn down, no graceful shutdown) and there was no way for
    the dashboard to know the "live" data it was displaying was hours
    stale rather than current.

    "not_running" covers three cases: no heartbeat file exists yet, the
    file couldn't be parsed, or the heartbeat is from a PREVIOUS calendar
    day (a session that ran yesterday and was never cleaned up shouldn't
    read as "running" today just because the file is still there).
    """
    from paper_trading.live_poller import HEARTBEAT_PATH

    if not HEARTBEAT_PATH.exists():
        return LiveSessionStatusResponse(
            status="not_running", message="No live session has run yet today (heartbeat.json not found).",
        )

    try:
        payload = json.loads(HEARTBEAT_PATH.read_text())
        last_heartbeat = datetime.fromisoformat(payload["timestamp"])
    except (OSError, ValueError, KeyError) as e:
        return LiveSessionStatusResponse(
            status="not_running", message=f"heartbeat.json exists but could not be read ({e}).",
        )

    if last_heartbeat.date() != date.today():
        return LiveSessionStatusResponse(
            status="not_running",
            message=f"Last heartbeat is from {last_heartbeat.date()}, not today -- no session running today.",
            last_heartbeat=last_heartbeat.isoformat(),
        )

    age = (datetime.now() - last_heartbeat).total_seconds()
    status = "alive" if age <= _LIVE_SESSION_STALE_SECONDS else "stale"
    message = (
        f"Live session heartbeat {age:.0f}s ago -- within the {_LIVE_SESSION_STALE_SECONDS:.0f}s freshness window."
        if status == "alive" else
        f"Live session heartbeat is {age:.0f}s old -- older than the {_LIVE_SESSION_STALE_SECONDS:.0f}s freshness "
        f"window. The session may have died without a graceful shutdown; do not treat displayed data as current."
    )
    return LiveSessionStatusResponse(
        status=status, message=message, last_heartbeat=last_heartbeat.isoformat(), age_seconds=age,
        open_positions=payload.get("open_positions"), symbols_polled=payload.get("symbols_polled"),
    )


