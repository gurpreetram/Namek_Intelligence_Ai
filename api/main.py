# Serves the frontend's PRODUCTION build directly from this backend process,
# added 2026-08-18 so a separate `npm run dev` process doesn't have to run
# alongside it -- on this machine's 7.8GB RAM, that second Node process
# (plus its own Vite dev-server watchers/HMR) was one more thing competing
# for memory with the live session, API server, and full-universe scans,
# and was a real contributor to the system hanging under load. Run
# `npm run build` in frontend/ whenever the frontend changes -- this mount
# serves whatever is currently in frontend/dist, it does NOT rebuild it.
#
# Registered LAST, after every @app.get/@app.post route above -- Starlette
# resolves routes in registration order, so every real API path (/best-
# picks, /health, etc.) is matched first regardless of mount order; this
# mount only ever catches paths nothing above it claimed.
#
# html=True makes StaticFiles serve dist/index.html for "/" (and for any
# other unmatched path -- this app has no client-side router/deep-linkable
# routes, see App.jsx's hotkey/tab-based navigation, so a single index.html
# entry point is all that's needed; there is no SPA-fallback requirement to
# solve here). If frontend/dist doesn't exist yet (frontend never built),
# this mount is skipped with a log line rather than crashing the API on
# import -- the backend is still fully usable via /docs and curl either way.
_FRONTEND_DIST = PROJECT_ROOT / "frontend" / "dist"
if _FRONTEND_DIST.exists():
    app.mount("/", StaticFiles(directory=_FRONTEND_DIST, html=True), name="frontend")
else:
    print(f"[api.main] frontend/dist not found at {_FRONTEND_DIST} -- skipping static mount. "
          f"Run `npm run build` in frontend/ to enable serving the dashboard from this backend.")
