_SECTORS_CACHE_TTL_SECONDS = 300.0
_sectors_cache: dict = {"response": None, "computed_at": 0.0}


@app.get("/sectors", response_model=SectorsResponse)
def get_sectors() -> SectorsResponse:
    """
    Ranks all NSE sectors covered by config/sector_mapping.json (see
    examples/build_sector_mapping.py) by today's equal-weighted average
    % return of their cached constituents, most-trending first in either
    direction, each with its top momentum stocks (see detectors/
    sector_momentum.py).

    INFORMATIONAL ONLY -- this is not a trading signal or strategy. It
    does not produce entry/target/stop-loss and should not be treated as
    one; SectorConfluenceTrend (a real attempt to use sector agreement as
    a hard trade filter) made results WORSE on thin coverage when tested
    earlier. This endpoint exists to help a human browse "which sectors
    are hot today", nothing more.

    Coverage is real but limited by design: only ~180 of ~2373 cached
    symbols (7.6%) have an official sector label, because NSE sectoral
    indices only cover the largest/most liquid stocks per sector (10-40
    constituents each, drawn from Nifty 500) -- most small/mid-caps
    genuinely have no official classification this way. sector_coverage_pct
    is returned so the frontend can show this honestly rather than implying
    full-universe coverage.
    """
    from config.settings import PROJECT_ROOT, STORAGE_ROOT

    now = time.monotonic()
    if _sectors_cache["response"] is not None and (now - _sectors_cache["computed_at"]) <= _SECTORS_CACHE_TTL_SECONDS:
        return _sectors_cache["response"]

    mapping_path = PROJECT_ROOT / "config" / "sector_mapping.json"
    if not mapping_path.exists():
        raise HTTPException(status_code=404, detail="No sector mapping found -- run "
                                                      "examples/build_sector_mapping.py first.")
    sector_mapping = json.loads(mapping_path.read_text())

    from config.settings import now_ist
    from detectors.sector_momentum import compute_sector_momentum, pick_reference_as_of

    symbol_data = {s: storage.load(s) for s in sector_mapping}
    symbol_data = {s: df for s, df in symbol_data.items() if not df.empty}
    if not symbol_data:
        raise HTTPException(status_code=404, detail="No cached data for any sector-mapped symbol.")

    # Same reference timestamp compute_sector_momentum() will use
    # internally (as_of=None) -- computed once here so the reported as_of
    # actually matches what was used, not a naive max() across symbols
    # (see pick_reference_as_of()'s docstring for why that would mislead).
    as_of = pick_reference_as_of(symbol_data)

    today_ist = now_ist().date()
    if as_of.date() != today_ist:
        # The cache hasn't been refreshed today (e.g. no live session has
        # run yet -- see paper_trading/live_poller.py, the only thing that
        # writes fresh intraday bars into this same storage/candles/ cache
        # during the day). Without this check, compute_sector_momentum()
        # would silently compute yesterday's full-day open-to-close move
        # and the dashboard would show it as if it were today's, straight
        # through market open and beyond -- a real, confirmed bug this
        # guard exists to fix.
        response = SectorsResponse(
            status="stale_previous_day",
            message=f"Cached data hasn't been refreshed today yet -- the latest available bar is from "
                    f"{as_of.date().isoformat()}. Start a live session (or re-run the bulk fetch) to see "
                    f"today's sector moves.",
            generated_at=datetime.now().isoformat(),
            as_of=None,
            sector_coverage_pct=0.0,
            sectors=[],
        )
        _sectors_cache["response"] = response
        _sectors_cache["computed_at"] = now
        return response

    results = compute_sector_momentum(sector_mapping, symbol_data, as_of=as_of)

    cached_universe_size = len(list(STORAGE_ROOT.glob("*_1min.parquet"))) if STORAGE_ROOT.exists() else 0
    coverage_pct = (len(set(sector_mapping) & set(symbol_data)) / cached_universe_size * 100.0) if cached_universe_size else 0.0

    response = SectorsResponse(
        generated_at=datetime.now().isoformat(),
        as_of=as_of.isoformat(),
        sector_coverage_pct=coverage_pct,
        sectors=[
            SectorMomentumResponse(
                sector=r.sector, return_pct=r.return_pct, num_constituents=r.num_constituents,
                top_stocks=[StockMomentumResponse(symbol=s.symbol, return_pct=s.return_pct, magnitude=s.magnitude)
                            for s in r.top_stocks],
                magnitude=r.magnitude,
            )
            for r in results
        ],
    )
    _sectors_cache["response"] = response
    _sectors_cache["computed_at"] = now
    return response


