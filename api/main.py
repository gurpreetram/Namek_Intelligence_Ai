def _is_market_hours(now: datetime) -> bool:
    """
    `now` must be an IST-aware datetime (see config.settings.now_ist()) --
    this function does NOT convert timezones itself, it only reads
    weekday/date/time-of-day off whatever `now` already represents. A
    naive datetime.now() silently assumes the host's local clock already
    IS IST, which only holds by coincidence on a machine explicitly
    configured that way; passing now_ist() makes the check correct
    regardless of the underlying server's system timezone.
    """
    from config.settings import MARKET_CLOSE, MARKET_OPEN, is_trading_day
    if not is_trading_day(now.date()):  # covers both weekends and NSE holidays
        return False
    current = now.strftime("%H:%M")
    return MARKET_OPEN <= current <= MARKET_CLOSE


@app.get("/sector-momentum-picks", response_model=SectorMomentumPicksResponse)
def get_sector_momentum_picks() -> SectorMomentumPicksResponse:
    """
    LIVE, rolling counterpart to /sectors: top-2 up / top-2 down sectors
    by TRAILING return over the last _SECTOR_PICKS_LOOKBACK_MINUTES
    (not since-open), computed from a live Upstox intraday fetch of the
    sector-mapped universe.

    IMPORTANT: this endpoint exists at explicit user request, made AFTER
    being shown that both research scripts testing this exact mechanism
    (a sector moving now predicting its stocks' near-term momentum) found
    NO real, consistent edge over random selection across 4 lookback/
    forward combinations on 21 days of cached history. This endpoint does
    not change that finding -- disclaimer is always populated so the
    frontend can keep it visible at all times, not just on first load.
    """
    from config.settings import now_ist
    now = now_ist()
    generated_at = now.isoformat()

    if not _is_market_hours(now):
        return SectorMomentumPicksResponse(
            status="market_closed",
            message="Market is closed (NSE trading hours: 09:15-15:30 IST, Mon-Fri). "
                    "Live momentum picks are only available during market hours.",
            generated_at=generated_at,
            lookback_minutes=_SECTOR_PICKS_LOOKBACK_MINUTES,
            disclaimer=_SECTOR_PICKS_DISCLAIMER,
        )

    market_open_today = now.replace(hour=9, minute=15, second=0, microsecond=0)
    if (now - market_open_today).total_seconds() < _SECTOR_PICKS_LOOKBACK_MINUTES * 60:
        return SectorMomentumPicksResponse(
            status="insufficient_data",
            message=f"Not enough data yet -- need at least {_SECTOR_PICKS_LOOKBACK_MINUTES} minutes "
                    f"since market open (09:15) for the rolling lookback window.",
            generated_at=generated_at,
            lookback_minutes=_SECTOR_PICKS_LOOKBACK_MINUTES,
            disclaimer=_SECTOR_PICKS_DISCLAIMER,
        )

    cache_age = time.monotonic() - _sector_picks_cache["computed_at"]
    if _sector_picks_cache["response"] is not None and cache_age <= _SECTOR_PICKS_CACHE_TTL_SECONDS:
        cached: SectorMomentumPicksResponse = _sector_picks_cache["response"]
        return cached.model_copy(update={"generated_at": generated_at})

    from config.settings import PROJECT_ROOT
    from data.fetcher import fetch_intraday_1min_bulk
    from data.instruments import resolve_many
    from detectors.sector_momentum import compute_sector_momentum, select_top_bottom_sectors

    mapping_path = PROJECT_ROOT / "config" / "sector_mapping.json"
    if not mapping_path.exists():
        raise HTTPException(status_code=404, detail="No sector mapping found -- run "
                                                      "examples/build_sector_mapping.py first.")
    sector_mapping = json.loads(mapping_path.read_text())

    instrument_keys = resolve_many(list(sector_mapping))
    resolved_keys = {symbol: key for symbol, key in instrument_keys.items() if key is not None}
    # Concurrent fetch (thread pool, I/O-bound) instead of one-at-a-time --
    # see fetch_intraday_1min_bulk()'s docstring. Same "one bad symbol
    # doesn't kill the batch" behavior as before, just faster; the
    # aggregation logic below is completely unchanged.
    symbol_data: dict[str, pd.DataFrame] = fetch_intraday_1min_bulk(resolved_keys, max_workers=10)

    if not symbol_data:
        raise HTTPException(status_code=502, detail="Live fetch failed for all sector-mapped symbols.")

    # fetch_intraday_1min() (what fetch_intraday_1min_bulk() calls per
    # symbol) only ever returns TODAY's candles -- see its own docstring --
    # so without this, compute_daily_atr_pct() never has any prior-day
    # bars to work with and every stock/sector here always reports
    # magnitude "unknown", even during market hours. Splice in each
    # symbol's PRIOR-day history from the static cache (storage.load()) --
    # disjoint date ranges (prior days vs today), so this is a plain
    # concat, not a merge/dedupe like storage.save() needs. today's
    # return_pct still comes entirely from the fresh live fetch above.
    today_date = now.date()
    for symbol, live_df in symbol_data.items():
        cached_df = storage.load(symbol)
        if cached_df.empty:
            continue
        prior_days = cached_df[cached_df.index.date < today_date]
        if not prior_days.empty:
            symbol_data[symbol] = pd.concat([prior_days, live_df]).sort_index()

    results = compute_sector_momentum(
        sector_mapping, symbol_data, lookback_minutes=_SECTOR_PICKS_LOOKBACK_MINUTES,
    )
    picks = select_top_bottom_sectors(results, n=2)
    up = [p for p in picks if p.return_pct >= 0]
    down = [p for p in picks if p.return_pct < 0]
    data_as_of = max(df.index.max() for df in symbol_data.values())

    def _to_response(r) -> SectorMomentumResponse:
        return SectorMomentumResponse(
            sector=r.sector, return_pct=r.return_pct, num_constituents=r.num_constituents,
            top_stocks=[StockMomentumResponse(symbol=s.symbol, return_pct=s.return_pct, magnitude=s.magnitude)
                        for s in r.top_stocks],
            magnitude=r.magnitude,
        )

    response = SectorMomentumPicksResponse(
        status="ok",
        message="",
        generated_at=generated_at,
        data_as_of=data_as_of.isoformat(),
        lookback_minutes=_SECTOR_PICKS_LOOKBACK_MINUTES,
        up_sectors=[_to_response(r) for r in up],
        down_sectors=[_to_response(r) for r in down],
        disclaimer=_SECTOR_PICKS_DISCLAIMER,
    )
    _sector_picks_cache["response"] = response
    _sector_picks_cache["computed_at"] = time.monotonic()
    return response


