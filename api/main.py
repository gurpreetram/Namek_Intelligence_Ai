@app.post("/backtest", response_model=BacktestResponse)
def backtest(request: BacktestRequest) -> BacktestResponse:
    """
    Runs the given strategy across the given symbols and date range,
    using local cached data. Returns every trade plus aggregate
    performance metrics across all symbols combined.
    """
    if request.start_date > request.end_date:
        raise HTTPException(status_code=400, detail="start_date must be before end_date")

    builder = _STRATEGY_BUILDERS.get(request.strategy)
    if builder is None:
        raise HTTPException(status_code=400, detail=f"Unknown strategy '{request.strategy}'")

    all_trades: list[Trade] = []
    for symbol in request.symbols:
        strategy_instance, timeframes = builder()  # fresh instance per symbol -- no shared state leakage
        engine = BacktestEngine(strategy=strategy_instance, timeframes=timeframes)
        try:
            result = engine.run(symbol, request.start_date, request.end_date)
        except ValueError as e:
            raise HTTPException(status_code=404, detail=f"{symbol}: {e}")
        all_trades.extend(result.trades)

    report = compute(all_trades)

    return BacktestResponse(
        trades=[_trade_to_response(t) for t in all_trades],
        performance=PerformanceReportResponse(
            total_trades=report.total_trades,
            win_rate=report.win_rate,
            profit_factor=report.profit_factor if report.profit_factor != float("inf") else -1.0,
            max_drawdown_points=report.max_drawdown_points,
            sharpe_ratio=report.sharpe_ratio,
            expectancy_points=report.expectancy_points,
            avg_r_multiple=report.avg_r_multiple,
            avg_win_points=report.avg_win_points,
            avg_loss_points=report.avg_loss_points,
        ),
    )


